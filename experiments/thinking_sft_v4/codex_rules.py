def parse_direction(assignment):
    # Repeated input occurrences are often named "the two 9s" / "one 10".
    # Parse only the first search clause, never mistake a later operation for the first.
    first = re.split(r'(?i)\bthen\b|;', assignment, maxsplit=1)[0]
    repeated = re.search(r'(?i)\b(multiply|multiplying|add|adding|subtract|subtracting)\s+the\s+two\s+(\d+)s\b', first)
    if repeated:
        word, value = repeated.groups()
        op = {'mul':'*', 'add':'+', 'sub':'-'}[word.lower()[:3]]
        return op, int(value), int(value)
    qualifier = r'(?:(?:the\s+)?(?:first|second|other|one)\s+)?'
    match = re.search(r'(?i)\b(multiply|multiplying|add|adding|subtract|subtracting)\s+'
                      + qualifier + r'(\d+)\s+(and|by|to|from)\s+' + qualifier + r'(\d+)', first)
    if not match:
        return None
    word, a, link, b = match.groups()
    op = {'mul':'*', 'add':'+', 'sub':'-'}[word.lower()[:3]]
    a, b = int(a), int(b)
    if op == '-' and link.lower() == 'from':
        a, b = b, a
    return op, a, b

def has_literal_pair(expression, direction):
    """Require a real AST subtree, not a textual substring after removing parentheses."""
    op, a, b = direction
    kinds = {'+':ast.Add, '-':ast.Sub, '*':ast.Mult}
    try:
        tree = ast.parse(expression, mode='eval')
    except SyntaxError:
        return False
    for node in ast.walk(tree):
        if not isinstance(node, ast.BinOp) or not isinstance(node.op, kinds[op]):
            continue
        if not all(isinstance(x, ast.Constant) and type(x.value) is int for x in (node.left, node.right)):
            continue
        pair = node.left.value, node.right.value
        if pair == (a,b) or (op in ('+','*') and pair == (b,a)):
            return True
    return False

@lru_cache(maxsize=20000)
def attainable(values):
    if len(values)==1:
        return frozenset(values)
    results = set()
    for i, a in enumerate(values):
        for j in range(i+1,len(values)):
            b = values[j]
            rest = [x for k,x in enumerate(values) if k not in (i,j)]
            for v in {a+b,a-b,b-a,a*b}:
                results.update(attainable(tuple(sorted(rest+[v]))))
    return frozenset(results)

def direction_has_solution(numbers, target, direction):
    op, a, b = direction
    remaining = list(numbers)
    try:
        remaining.remove(a)
        remaining.remove(b)
    except ValueError:
        return False
    value = {'+':lambda:a+b, '-':lambda:a-b, '*':lambda:a*b}[op]()
    return target in attainable(tuple(sorted(remaining+[value])))


