def seed_of(*parts):
    return int.from_bytes(hashlib.sha256('|'.join(map(str, parts)).encode()).digest()[:4], 'little') & 0x7fffffff

def last_boxed(text):
    """Content of the last \\boxed{...} / \\fbox{...} with balanced braces, else None."""
    if text is None:
        return None
    best = None
    for match in re.finditer(r'\\(?:boxed|fbox)\s*\{', text):
        depth, i = 1, match.end()
        while i < len(text) and depth:
            depth += {'{': 1, '}': -1}.get(text[i], 0)
            i += 1
        if depth == 0:
            best = text[match.end():i - 1]
    return best

def gold_answer(task, gold):
    if task['src'] == 'math':
        return last_boxed(gold['oracle'])
    answer = str(gold['oracle']).strip()
    return answer.replace(',', '') if re.fullmatch(r'-?\d{1,3}(,\d{3})+(\.\d+)?', answer) else answer

def final_boxed_answer(text):
    """Join adjacent final boxes, without joining boxes separated by reasoning."""
    if text is None:
        return None
    boxes = []
    for match in re.finditer(r'\\(?:boxed|fbox)\s*\{', text):
        depth, end = 1, match.end()
        while end < len(text) and depth:
            depth += {'{': 1, '}': -1}.get(text[end], 0)
            end += 1
        if depth == 0:
            boxes.append((match.start(), end, text[match.end():end-1]))
    if not boxes:
        return None
    selected = [boxes[-1][2]]
    for previous, following in zip(reversed(boxes[:-1]), reversed(boxes[1:])):
        if not re.fullmatch(r'\s*(?:,|;|and|\\text\{and\})\s*', text[previous[1]:following[0]]):
            break
        selected.insert(0, previous[2])
    return ','.join(selected)

def grade(task, gold, final):
    """(correct, reason) of a native final answer (text after </think>)."""
    if final is None:
        return False, 'unfinished'
    if task['src'] == 'countdown':
        found = re.findall(r'(?im)^\s*\**\s*Final Answer\s*:?\**\s*:?\s*([^\n]+?)\s*$', final)
        if not found:
            return False, 'no_final_answer_line'
        result = countdown_core.verify(found[-1].strip().strip('`$'), task['numbers'], task['target'])
        return bool(result['correct']), result['reason'] if not result['correct'] else 'correct'
    boxed = final_boxed_answer(final)
    if boxed is None:
        return False, 'no_boxed'
    from math_verify import parse, verify
    try:
        reference = parse(gold['oracle']) if task['src'] == 'math' else parse('\\boxed{' + gold_answer(task, gold) + '}')
        predicted = parse('\\boxed{' + boxed + '}')
        ok = bool(reference and predicted and verify(reference, predicted))
        return ok, 'correct' if ok else 'wrong'
    except Exception as e:  # noqa: BLE001
        return False, 'verifier_exception:' + type(e).__name__

def norm_math(s):
    s = s.replace('\u221a', '\\sqrt').replace('\u03c0', '\\pi').replace('{', '').replace('}', '')
    s = s.replace('\\left', '').replace('\\right', '').replace('\\!', '').replace('\\,', '').replace('$', '')
    s = s.replace('\\dfrac', '\\frac').replace('\\tfrac', '\\frac').replace('^\\circ', '').replace('^{\\circ}', '')
    return re.sub(r'\s+', '', s)

NUMBER = re.compile(r'-?\d+(?:\.\d+)?')

def numbers_in(text):
    text = re.sub(r'(?<=\d),(?=\d{3}\b)', '', text)
    return {n.lstrip('-') for n in NUMBER.findall(text)}

def contains_answer(text, task, gold):
    """True if `text` contains the gold final answer (verifier only)."""
    answer = gold_answer(task, gold)
    if answer is None:
        return False
    if task['src'] == 'countdown':
        for expr in re.findall(r'[0-9+\-*() ]{5,}', text):
            expr = expr.strip()
            if any(op in expr for op in '+-*') and countdown_core.verify(expr, task['numbers'], task['target'])['correct']:
                return True
        return False
    plain = answer.replace(',', '').strip()
    if re.fullmatch(r'-?\d+(?:\.\d+)?', plain):
        value = plain.lstrip('-')
        if value.endswith('.0'):
            value = value[:-2]
        return value in numbers_in(text)
    target = norm_math(answer)
    return len(target) >= 2 and target in norm_math(text)

def answer_in_question(task, gold):
    return contains_answer(task['question'], task, gold)

def patch_sampler():
    """vLLM 0.8.5 without FlashInfer sorts the whole vocabulary every step for top-p. With top_k <= 64 set on
    every row, top-p over the top-k set is the same distribution: take topk, mask past each row's k, keep a token
    iff the probability mass ranked above it is < p (vLLM: ascending cumsum > 1-p; at least one kept)."""
    import torch
    from vllm.v1.sample.ops import topk_topp_sampler as m
    original = m.apply_top_k_top_p

    def fast(logits, k, p):
        if k is None or p is None or int(k.max()) > 64:
            return original(logits, k, p)
        kmax = int(k.max())
        vals, idx = logits.topk(kmax, dim=-1)  # descending
        ranks = torch.arange(kmax, device=logits.device).unsqueeze(0)
        vals = vals.masked_fill(ranks >= k.to(torch.long).unsqueeze(1), -float('inf'))
        probs = vals.softmax(dim=-1)
        above = probs.cumsum(dim=-1) - probs
        drop = above >= p.unsqueeze(1)
        drop[:, 0] = False
        vals = vals.masked_fill(drop, -float('inf'))
        out = torch.full_like(logits, -float('inf'))
        return out.scatter_(-1, idx, vals)

    m.apply_top_k_top_p = fast

def split_think(text):
    """(thinking content, text after </think> or None if unfinished) of a raw Qwen3 thinking output."""
    s = text
    if s.lstrip().startswith('<think>'):
        s = s.lstrip()[len('<think>'):]
    if '</think>' not in s:
        return s, None
    thinking, answer = s.split('</think>', 1)
    return thinking, answer

RESULT = re.compile(r'(?im)^[ \t>*#-]*\**\s*Result\s*\**\s*:\s*\**\s*(.+?)\s*$')

def component_for(assignment, comp):
    hits = [k for k in comp if re.search(r'(?i)\b' + re.escape(k) + r'\b(?!\s*\d)', assignment)]
    return hits[0] if len(hits) == 1 else None

def last_number(text):
    text = text.replace('\u2212', '-').replace(',', '').replace('$', '')
    nums = re.findall(r'-?\d+(?:\.\d+)?', text)
    return float(nums[-1]) if nums else None

def countdown_expr(value):
    """Normalized arithmetic expression in a Result value, or None."""
    m = re.findall(r'[0-9+\-*() ]{3,}', re.sub(r'(?<=\d)\s*[x×]\s*(?=[\d(])', '*', value))
    m = [x.strip() for x in m if any(op in x for op in '+-*') and re.search(r'\d', x)]
    return max(m, key=len).replace(' ', '') if m else None

def countdown_branch(q, assignment, value):
    """('ok', expr|None) or (reason, None). A branch either reports a valid expression that follows its assigned
    direction, or explicitly reports that its direction has no solution."""
    direction = parse_direction(assignment)
    if direction is None:
        return 'countdown_unverifiable_direction', None
    if Counter(direction[1:]) - Counter(q['task']['numbers']):
        return 'countdown_unavailable_first_pair', None
    expr = countdown_expr(value)
    if expr is None:
        if re.search(r'(?i)\b(no|none|not possible|impossible|cannot|can\'t)\b', value):
            if direction_has_solution(tuple(q['task']['numbers']), q['task']['target'], direction):
                return 'countdown_false_no_solution', None
            return 'ok', None
        return 'countdown_no_expression', None
    if not countdown_core.verify(expr, q['task']['numbers'], q['task']['target'])['correct']:
        return 'countdown_invalid_expression', None
    if not has_literal_pair(expr, direction):
        return 'countdown_off_direction', None
    return 'ok', expr

def check_branch(q, plan, i, o):
    """(ok, reason, body, result_line) of executor output o for assignment i (0-based)."""
    if o['finish_reason'] != 'stop':
        return False, 'branch_truncated', None, None
    thinking, after = split_think(o['text'])
    if after is None:
        return False, 'branch_unfinished', None, None
    found = RESULT.findall(after) or RESULT.findall(thinking[-400:])
    if not found:
        return False, 'no_result_line', None, None
    value = found[-1].strip()
    inner = last_boxed(value)
    if inner is not None:
        value = re.sub(r'\\boxed\s*\{.*\}', lambda _: inner, value)
    value = value.strip().strip('*').strip()
    if not meaningful_result(value):
        return False, 'empty_result', None, None
    result_line = f'Result: {value}'
    core = thinking.strip()
    while True:  # the model often ends its thinking with its own Result line; keep exactly one
        stripped = re.sub(r'\n*[ \t>*#-]*\**\s*Result\s*\**\s*:[^\n]*$', '', core).rstrip()
        if stripped == core:
            break
        core = stripped
    body = ' ' + core + '\n\n' + result_line
    if not thinking.strip():
        return False, 'empty_thinking', None, None
    if not contract.plain_text(body):
        return False, 'body_not_plain_text', None, None
    if plan['kind'] == 'decompose':  # \boxed formatting after </think> is dropped, not rejected
        if contains_answer(result_line, q['task'], q['gold']) and not answer_in_question(q['task'], q['gold']):
            return False, 'decompose_branch_reports_final_answer', None, None
    if q['src'] == 'countdown':
        status, expr = countdown_branch(q, plan['items'][i], value)
        if status != 'ok':
            return False, status, None, None
        return True, 'ok_countdown_valid' if expr else 'ok_countdown_none', body, result_line
    comp = q['gold'].get('component_oracles') or {}
    key = component_for(plan['items'][i], comp)
    if key is not None:
        got = last_number(value)
        if got is None or abs(got - comp[key]) > 1e-6:
            return False, 'component_oracle_mismatch', None, None
        return True, 'ok_oracle_verified', body, result_line
    return True, 'ok', body, result_line

def executor_prompt_d(q, prefix, plan, i):
    """Arm D (A/B winner over the agreed prompt): sub-task first, problem as context, sibling assignments named
    as not-to-do (assignments only, never sibling results)."""
    a = plan['items'][i]
    others = ''.join(f"- {x}\n" for j, x in enumerate(plan['items']) if j != i)
    if plan['kind'] in ('decompose', 'cases'):
        rule = f"Solve only your sub-task: {a}\nDo not answer the original question. "
    else:
        rule = f"Work only along your sub-task: {a}\nYou may carry it through to a full candidate solution, but stay within your sub-task. "
    return (f"You are solving ONE sub-task of a larger problem.\n\nSub-task: {a}\n\n"
            f"Problem (context only; do not answer its question):\n{q['task']['question']}\n\n"
            f"Reasoning so far:\n{prefix.strip()}\n\n"
            f"Other workers handle these sub-tasks, so do NOT do them:\n{others}\n"
            + rule + "End with one line 'Result: ...' that gives only your sub-task's result.")

def executor_prompt_e(plan, i):
    """Arm E: the planner's standalone mini-problem only (no original problem, no prefix)."""
    return (f"{plan['subproblems'][i]}\n\nThink it through step by step. "
            f"End with one line 'Result: ...' that gives the answer.")

def merger_prompt(q, prefix, plan, results):
    tasks = ''.join(f"{i}. Task: {item}\n   {res}\n" for i, (item, res) in enumerate(zip(plan['items'], results), 1))
    use = ("Treat supplied Results as already computed. Perform ONLY the remaining aggregation, "
           "comparison or inference. Do not recalculate the individual subproblems, restate their "
           "full solutions, or verify them by repeating their calculations. A missing or contradictory "
           "Result must be acknowledged; do not pretend an unfinished branch was verified. "
           "Keep reasoning focused inside <think>. After </think>, output only the final answer, "
           "without another explanation. ")
    finish = (use + "Combine them and finish solving; give the final expression on a separate line beginning 'Final Answer:'."
              if q['src'] == 'countdown' else use + 'Combine them and finish solving; final answer in \\boxed{}.')
    return (f"{q['task']['question']}\n\nReasoning so far:\n{prefix.strip()}\n\n"
            f"The remaining work was split into independent tasks, which have been completed:\n{tasks}\n{finish}")

def seg(text, loss, block=None, path=None):
    return {'text': text, 'loss': loss, 'block': block, 'path': path}

def parallel_segments(prefix, plan, bodies, summary, answer):
    n = plan['branches']
    s = [seg('<think>', True), seg(prefix, True), seg('<Parallel>', True, 1), seg(contract.BRANCHES, False, 1),
         seg(str(n), True, 1), seg('<Plan>', False, 1), seg(plan['plan_text'], True, 1), seg('</Plan>', True, 1)]
    for i, body in enumerate(bodies, 1):
        s += [seg('<Path>', False, 1, i), seg(contract.path_prefix(i), False, 1, i), seg(body, True, 1, i),
              seg('</Path>', True, 1, i)]
    s += [seg('</Parallel>', False, 1), seg('<Summary>', False, 1), seg(summary, True, 1), seg('</Summary>', True, 1),
          seg('</think>', True), seg(answer, True), seg('<|im_end|>', True)]
    text = ''.join(x['text'] for x in s)
    block = contract.format_block(plan['kind'], plan['items'], bodies, summary)
    assert ('<think>' + prefix + block + '</think>' + answer + '<|im_end|>') == text
    return s, text


