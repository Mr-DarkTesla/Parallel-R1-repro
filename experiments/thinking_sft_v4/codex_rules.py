def countdown_verify(expression, numbers, target):
    """Stand-in for countdown_core.verify (see the module docstring): dict(correct, reason)."""
    if not isinstance(expression, str) or not re.fullmatch(r'[0-9+\-*() ]+', expression):
        return dict(correct=False, reason='invalid_characters')
    try:
        tree = ast.parse(expression, mode='eval').body
    except SyntaxError:
        return dict(correct=False, reason='invalid_grammar')
    used = []

    def value(node):
        if isinstance(node, ast.Constant) and type(node.value) is int:
            used.append(node.value)
            return node.value
        if isinstance(node, ast.BinOp) and isinstance(node.op, (ast.Add, ast.Sub, ast.Mult)):
            a, b = value(node.left), value(node.right)
            return a + b if isinstance(node.op, ast.Add) else a - b if isinstance(node.op, ast.Sub) else a * b
        raise ValueError('grammar')

    try:
        result = value(tree)
    except ValueError:
        return dict(correct=False, reason='invalid_grammar')
    if Counter(used) != Counter(int(n) for n in numbers):
        return dict(correct=False, reason='wrong_multiset')
    if result != int(target):
        return dict(correct=False, reason='wrong_value')
    return dict(correct=True, reason='correct')


countdown_core = SimpleNamespace(verify=countdown_verify)

