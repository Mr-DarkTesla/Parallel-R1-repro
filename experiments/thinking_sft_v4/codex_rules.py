def meaningful_result(value):
    # A delimiter-only result such as '$$' is not an answer to a subproblem.
    return bool(re.search(r'[\w\d]', value, flags=re.UNICODE))

def expression_key(expression):
    """Ignore parentheses and order for associative/commutative + and * only.

    Do not reduce expressions to their numeric value: all valid solutions have
    that same value, but may represent genuinely different approaches.
    """
    def visit(node):
        if isinstance(node, ast.Constant) and type(node.value) is int:
            return ('n', node.value)
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
            return ('neg', visit(node.operand))
        if not isinstance(node, ast.BinOp) or not isinstance(node.op, (ast.Add, ast.Sub, ast.Mult)):
            raise ValueError('unsupported expression')
        op = {ast.Add: '+', ast.Sub: '-', ast.Mult: '*'}[type(node.op)]
        left, right = visit(node.left), visit(node.right)
        if op == '-':
            return (op, left, right)
        children = []
        for child in (left, right):
            children.extend(child[1:] if child[0] == op else (child,))
        return (op, *sorted(children, key=repr))
    return visit(ast.parse(expression, mode='eval').body)


